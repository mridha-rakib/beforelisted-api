import { afterEach, describe, expect, it, vi } from "vitest";

import { AgentProfileRepository } from "../src/modules/agent/agent.repository.js";
import { AuthService } from "../src/modules/auth/auth.service.js";
import { EmailService } from "../src/services/email.service.js";
import { EmailTemplates } from "../src/services/email.templates.beforelisted.js";

vi.mock("@/services/email.transporter", () => ({
  createEmailTransporter: () => ({ verify: vi.fn(), send: vi.fn() }),
}));

afterEach(() => vi.restoreAllMocks());

describe("renter verified-registration welcome email", () => {
  it("includes the approved content, preserves metadata and safely renders placeholders", async () => {
    const service = Object.create(EmailService.prototype) as any;
    service.templates = new EmailTemplates();
    service.config = { brandColor: "#1890FF", maxRetries: 1 };
    service.sendEmail = vi.fn().mockResolvedValue({ success: true });
    await service.sendWelcomeEmail({
      to: "renter@example.invalid",
      userName: "Riley <Renter>",
      userType: "Renter",
      loginLink: "https://example.invalid/login",
      registeredAgent: { fullName: "Alex & Taylor", title: "Agent <Lead>", brokerage: "Example Brokerage" },
    });
    const [options, kind, recipient] = service.sendEmail.mock.calls[0];
    expect(options).toMatchObject({
      to: { email: "renter@example.invalid", name: "Riley <Renter>" },
      replyTo: "support@beforelisted.com",
      subject: "Welcome to BeforeListed",
    });
    expect([kind, recipient]).toEqual(["WELCOME", "renter@example.invalid"]);
    expect(options.html).toContain("Alex &amp; Taylor, Agent &lt;Lead&gt; with Example Brokerage");
    expect(options.html).not.toContain("Agent <Lead>");
    expect(options.html).toContain("Access exclusive moving discounts for BeforeListed users, including moving companies like Piece of Cake, internet providers and more.");
    expect(options.html).toContain("href=\"https://beforelisted.com/report/latest\"");
    expect(options.html).toContain("Read the Latest Report &amp; News");
    expect(options.html.indexOf("Know where the rental market stands")).toBeGreaterThan(options.html.indexOf("Access exclusive moving discounts"));
    expect(options.html.indexOf("Know where the rental market stands")).toBeLessThan(options.html.indexOf("If you have any questions or need assistance"));
    expect(options.text).toContain("Alex & Taylor, Agent <Lead> with Example Brokerage");
    expect(options.text).toContain("Read the Latest Report & News: https://beforelisted.com/report/latest");
  });

  it("does not add renter report content to the agent welcome", () => {
    const templates = new EmailTemplates();
    const html = templates.welcome("Synthetic Agent", "Agent", "https://example.invalid/login");
    expect(html).not.toContain("Know where the rental market stands");
    expect(html).toContain("pending admin review");
  });

  it("preserves the generated-password branch and does not expose the synthetic credential in output", async () => {
    const service = Object.create(EmailService.prototype) as any;
    service.templates = new EmailTemplates();
    service.config = { brandColor: "#1890FF", maxRetries: 1 };
    service.sendEmail = vi.fn().mockResolvedValue({ success: true });
    await service.sendWelcomeEmail({ to: "renter@example.invalid", userName: "Synthetic Renter", userType: "Renter", loginLink: "https://example.invalid/login", isPasswordAutoGenerated: true, temporaryPassword: "synthetic-test-only" });
    const options = service.sendEmail.mock.calls[0][0];
    expect(options.subject).toBe("Welcome to BeforeListed - Your Temporary Password");
    expect(options.html.includes("synthetic-test-only")).toBe(true);
    expect(options.html).not.toContain("Know where the rental market stands");
    expect(options.replyTo).toBe("support@beforelisted.com");
    expect(options.text).toBeUndefined();
  });

  it("passes the verified renter and registered agent to the welcome email after OTP verification", async () => {
    const service = Object.create(AuthService.prototype) as any;
    const user = { _id: "507f1f77bcf86cd799439011", email: "renter@example.invalid", fullName: "Riley Renter", role: "Renter", createdAt: new Date("2025-01-01") };
    service.emailVerificationService = { verifyOTP: vi.fn().mockResolvedValue({ userId: user._id, userType: "Renter" }) };
    service.userService = { getUserByEmail: vi.fn().mockResolvedValue(user), markEmailAsVerified: vi.fn().mockResolvedValue(user), toUserResponse: vi.fn().mockReturnValue({ role: "Renter" }) };
    service.renterRepository = { findRenterWithReferrer: vi.fn().mockResolvedValue({ referredByAgentId: { _id: "507f1f77bcf86cd799439012", fullName: "Alex Agent", email: "agent@example.invalid" } }) };
    service.emailService = { sendWelcomeEmail: vi.fn().mockResolvedValue({ success: true }), sendRenterRegistrationVerifiedAdminNotification: vi.fn().mockResolvedValue({ success: true }) };
    vi.spyOn(AgentProfileRepository.prototype, "findByUserId").mockResolvedValue({ title: "Agent", brokerageName: "Example Brokerage" } as never);
    await service.verifyEmail({ email: user.email, code: "1234" });
    expect(service.emailVerificationService.verifyOTP).toHaveBeenCalledWith({ email: user.email, code: "1234" });
    expect(service.emailService.sendWelcomeEmail).toHaveBeenCalledWith(expect.objectContaining({
      to: user.email,
      userType: "Renter",
      registeredAgent: { fullName: "Alex Agent", title: "Agent", brokerage: "Example Brokerage", email: "agent@example.invalid" },
    }));
  });
});
